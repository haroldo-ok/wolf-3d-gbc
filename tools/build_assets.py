RENDER_TABLES = {'tex_bank', 'wall_x_tex', 'wall_y_tex', 'lvl_fam', 'lvl_pal', 'lvl_ceil', 'lvl_floor', 'sin1024',
                 'recip_q8', 'ray_k', 'hgt_a', 'hgt_b', 'hgt_c'}
SPRITE_TABLES = {'spr_bank', 'spr_off', 'spr_x0', 'spr_x1', 'spr_t0', 'spr_t1', 'spr_pool', 'pool_pal'}   # src/rspr.c's bank


class Out:
    def __init__(self):
        self.h = ['/* generated by tools/build_assets.py - do not edit */', '#ifndef ASSETS_H', '#define ASSETS_H',
                  '#include "gbc.h"']
        self.c = ['/* generated by tools/build_assets.py - do not edit */', '#include "assets.h"']
        self.cr = list(self.c)          # tables of the render bank
        self.cp = list(self.c)          # tables of the sprite bank
        self.ch = list(self.c)          # tables of the HUD / weapon bank
        self.cu = list(self.c)          # tables of the front end bank
        self.cs = list(self.c)          # tables of the sound bank

    def H(self, s):
        self.h.append(s)

    def C(self, s):
        self.c.append(s)

    def arr(self, ctype, name, vals, per=16, const=True, comment=None):
        vals = list(vals)
        self.h.append('extern %s%s %s[%d];' % ('const ' if const else '', ctype, name, len(vals)))
        lines = []
        for i in range(0, len(vals), per):
            lines.append('  ' + ','.join(str(v) for v in vals[i:i + per]))
        seg = self.cs if name.startswith(('sfx_', 'mus_', 'digi_', 'pcm_')) else self.cu if name.startswith(('ui_', 'pic_')) else self.ch if name.startswith(('hud_', 'wpn_')) else self.cr if name in RENDER_TABLES else self.cp if name in SPRITE_TABLES else self.c
        seg.append('%s%s %s[%d] = {\n%s\n};' % ('const ' if const else '', ctype, name, len(vals), ',\n'.join(lines)))

    def write(self):
        os.makedirs(GEN, exist_ok=True)
        open(os.path.join(GEN, 'assets.h'), 'w').write('\n'.join(self.h) + '\n#endif\n')
        open(os.path.join(GEN, 'assets_tab.c'), 'w').write('\n'.join(self.c) + '\n')
        open(os.path.join(GEN, 'assets_r.c'), 'w').write('\n'.join(self.cr) + '\n')
        open(os.path.join(GEN, 'assets_p.c'), 'w').write('\n'.join(self.cp) + '\n')
        open(os.path.join(GEN, 'assets_h.c'), 'w').write('\n'.join(self.ch) + '\n')
        open(os.path.join(GEN, 'assets_u.c'), 'w').write('\n'.join(self.cu) + '\n')
        open(os.path.join(GEN, 'assets_s.c'), 'w').write('\n'.join(self.cs) + '\n')


def build():
    out = Out()
    d = G.data()
    pk = gbpack.Packer(DATA_BANK0)
    out.H('#define DATA_BANK0 %d' % DATA_BANK0)
    out.H('#define VIEW_TW %d' % V.VIEW_TW)
    out.H('#define VIEW_TH %d' % V.VIEW_TH)
    out.H('#define VIEW_W %d' % V.VIEW_W)
    out.H('#define VIEW_H %d' % V.VIEW_H)
    out.H('#define NRAYS %d' % V.NRAYS)
    out.H('#define RAYW %d' % V.RAYW)
    out.H('#define NUMTEX %d' % len(V.TEX_PAGES))
    out.H('#define NFAM %d' % V.NFAM)

    # ---------------------------------------------------------------- sprite names
    names = sprnames.sprite_names(paths.SRC)
    assert len(names) == 436
    out.H('enum {')
    out.H(',\n'.join('  %s = %d' % (n.replace('MACHINEGUNATK3', 'SPR_MACHINEGUNATK3') if n == 'MACHINEGUNATK3' else n, i)
                     for i, n in enumerate(names)))
    out.H('};')
    out.H('#define NUMSPRITES 436')

    # ---------------------------------------------------------------- sounds
    snd, mus = wl_names.audio_names()
    out.H('enum {')
    out.H(',\n'.join('  %s = %d' % (n, v) for n, v in snd))
    out.H('};')
    out.H('enum {')
    out.H(',\n'.join('  %s = %d' % (n, v) for n, v in mus))
    out.H('};')

    # ---------------------------------------------------------------- wall textures
    levels = V.pair_levels()
    tex_bank = []
    for ti, p in enumerate(V.TEX_PAGES):
        b, a = pk.add_bank('tex%d' % ti, V.texture_blob(levels[p]))
        tex_bank.append(b)
    out.arr('u8', 'tex_bank', tex_bank)
    xs, ys = V.wall_tabs()
    out.arr('u8', 'wall_x_tex', list(xs))
    out.arr('u8', 'wall_y_tex', list(ys))
    out.H('#define DOORW_NORMAL %d' % V.page_tex(V.DOORWALL))
    out.H('#define DOORW_FRAME %d' % V.page_tex(V.DOORWALL + 2))
    out.H('#define DOORW_ELEV %d' % V.page_tex(V.DOORWALL + 4))
    out.H('#define DOORW_LOCK %d' % V.page_tex(V.DOORWALL + 6))

    # ---------------------------------------------------------------- per level data
    pk.seal()
    nm = len(d.maps)
    out.H('#define NUMMAPS %d' % nm)
    mbank, maddr = [], []
    fam_tab, pal_tab, ceil_tab, floor_tab = [], [], [], []
    ceil_idx = wl_maps.CEILING_E1
    for mi, m in enumerate(d.maps):
        blob, st = wl_maps.build_level(m)
        b, a = pk.add('map%d' % mi, blob)
        mbank.append(b)
        maddr.append(a)
        pages = V.level_pages(m)
        fam, pal = V.family_palettes(levels, pages)
        fam_tab += fam
        for f in range(V.NFAM):
            pal_tab += pal[f]
        ceil_tab.append(G.rgb555(d.pal8[ceil_idx[mi]]))
        floor_tab.append(G.rgb555(d.pal8[0x19]))
        print('map', mi, len(blob), st, 'textures', len(pages))
    out.arr('u8', 'map_bank', mbank)
    out.arr('u16', 'map_addr', maddr)
    out.arr('u8', 'lvl_fam', fam_tab, per=32)
    out.arr('u16', 'lvl_pal', pal_tab, per=18)
    out.arr('u16', 'lvl_ceil', ceil_tab)
    out.arr('u16', 'lvl_floor', floor_tab)
    out.arr('u8', 'map_ceil', ceil_idx[:nm])

    # ---------------------------------------------------------------- sprites
    sp = V.build_sprites(pk)
    out.arr('u8', 'spr_bank', sp['bank'], per=32)
    out.arr('u16', 'spr_off', sp['off'], per=16)
    out.arr('u8', 'spr_x0', sp['x0'], per=32)
    out.arr('u8', 'spr_x1', sp['x1'], per=32)
    out.arr('u8', 'spr_t0', sp['t0'], per=32)
    out.arr('u8', 'spr_t1', sp['t1'], per=32)
    out.arr('u8', 'spr_pool', sp['pool'], per=32)
    out.H('#define NPOOL %d' % V.NPOOL)
    out.arr('u16', 'pool_pal', [c for p in sp['poolpal'] for c in p], per=12)
    print('sprites', sp['count'])

    # ---------------------------------------------------------------- scalers
    blob, so, to, hs = V.build_scalers()
    out.H('#define SC_SMALL_MAX %d' % V.MAXH_SMALL)
    out.H('#define SC_TALL_STEP %d' % V.TALL_STEP)
    out.H('#define SC_TALL_MAX %d' % V.TALL_MAX)
    out.arr('u8', 'scaler_data', list(blob), per=32)
    out.arr('u16', 'scaler_small', so)
    out.arr('u16', 'scaler_tall', to)

    # ---------------------------------------------------------------- tables
    out.arr('u16', 'sin_q', [min(65535, int(round(math.sin(math.radians(a)) * 65536))) for a in range(91)], per=16)
    out.arr('u16', 'tan_q', [min(65535, int(round(math.tan(math.radians(a)) * 65536))) for a in range(46)], per=16)
    open(os.path.join(GEN, 'rndtable.c'), 'w').write(
        '#include "assets.h"\nconst u8 rndtable[256] = {%s};\n' % ','.join(str(v) for v in RNDTABLE))
    out.H('extern const u8 rndtable[256];')

    # caster tables: angle unit 1/1024 turn
    N = 1024
    out.arr('s16', 'sin1024', [int(round(math.sin(2 * math.pi * i / N) * 256)) for i in range(N + N // 4)], per=16)
    out.arr('u16', 'recip_q8', [min(65535, 65536 // max(1, i)) for i in range(0, 513)], per=16)
    # per ray camera offsets: k_i = (2*i+1-NRAYS)/NRAYS in Q8 (range -1..1), the plane has half length tan(36 deg)
    k = [int(round((2 * i + 1 - V.NRAYS) * 256 / V.NRAYS * math.tan(math.radians(36)))) for i in range(V.NRAYS)]
    out.arr('s16', 'ray_k', k)
    # projection constant: height of a one tile high wall at distance 1 (pixels)
    focal = int(round((V.VIEW_W / 2) / math.tan(math.radians(36))))
    out.H('#define FOCAL %d' % focal)
    # wall height (pixels, capped at 255) for a distance t (Q8 tiles): three tables of growing step
    hg = lambda t: min(255, int(round(focal * 256.0 / max(t, 1))))
    out.arr('u8', 'hgt_a', [hg(2 * i + 1) for i in range(256)], per=32)                 # t < 512, step 2
    out.arr('u8', 'hgt_b', [hg(512 + 8 * i + 4) for i in range(192)], per=32)           # t < 2048, step 8
    out.arr('u8', 'hgt_c', [hg(2048 + 64 * i + 32) for i in range(224)], per=32)        # t < 16384, step 64
    out.H('#define TAN36_STEP %d' % int(round(2 * math.tan(math.radians(36)) / V.NRAYS * 65536)))


    # ---------------------------------------------------------------- HUD
    h = gb_hud.build()
    gb_hud.render_preview(h, os.path.join(GEN, 'hud_preview.png'))
    out.arr('u16', 'hud_pal', [c for p in h['pals'] for c in p], per=16)
    out.arr('u8', 'hud_dig', h['dig'], per=22)
    kt = h['key_tiles']
    out.arr('u8', 'hud_key', [v for nm in ('no', 'gold', 'silver') for v in kt[nm]], per=9)
    out.arr('u8', 'hud_pct', h['pct'])
    pk.seal()
    st = b''.join(h['tiles'][:h['static_n']])
    hb, ha = pk.add('hud_static', st, align=16)
    out.H('#define HUD_BANK %d' % hb)
    out.H('#define HUD_STATIC_ADDR 0x%04X' % ha)
    out.H('#define HUD_STATIC_N %d' % h['static_n'])
    out.H('#define HUD_FACE0 %d' % h['face0'])
    out.H('#define HUD_ICON0 %d' % h['icon0'])
    mp = bytearray(); at = bytearray()
    for r in range(6):
        mp += bytes(int(v) for v in h['cmap'][r]) + bytes(12)
        at += bytes(int(v) for v in h['amap'][r]) + bytes(12)
    b, a = pk.add('hud_map', bytes(mp) + bytes(at))
    assert b == hb
    out.H('#define HUD_MAP_ADDR 0x%04X' % a)
    ft = b''.join(b''.join(t) for t in h['face_tiles']) + bytes(sum((x + [0] * 0 for x in h['face_attr']), []))
    b, a = pk.add('hud_face', ft, align=16)
    out.H('#define HUD_FACE_BANK %d' % b)
    out.H('#define HUD_FACE_ADDR 0x%04X' % a)
    out.H('#define HUD_FACE_ATTR_ADDR 0x%04X' % (a + 23 * 256))
    it = b''.join(b''.join(t) for t in h['icon_tiles']) + bytes(sum(h['icon_attr'], []))
    b, a = pk.add('hud_icon', it, align=16)
    out.H('#define HUD_ICON_BANK %d' % b)
    out.H('#define HUD_ICON_ADDR 0x%04X' % a)
    out.H('#define HUD_ICON_ATTR_ADDR 0x%04X' % (a + 4 * 288))

    wpal, wblobs = gb_hud.build_weapons()
    out.arr('u16', 'wpn_pal', [c for w in wpal for p in w for c in p], per=16)
    pk.seal()
    woff = []
    for i, bl in enumerate(wblobs):
        b, a = pk.add('wpn%d' % i, bl, align=16)
        woff.append(a)
        wb = b
    out.H('#define WPN_BANK %d' % wb)
    out.H('#define WPN_T0 %d' % gb_hud.WPN_T0)
    out.H('#define WPN_NPAL %d' % gb_hud.WPN_NPAL)
    out.arr('u16', 'wpn_off', woff, per=10)

    # ---------------------------------------------------------------- front end
    import gb_ui as U
    pk.seal()
    ft = U.font_tiles()
    b, a = pk.add('ui_font', ft)
    out.H('#define UI_FONT_BANK %d' % b)
    out.H('#define UI_FONT_ADDR 0x%04X' % a)
    out.H('#define UI_FONT_TILES %d' % (len(ft) // 16))
    up = U.ui_palettes()
    out.arr('u16', 'ui_pals', [c for k in up for p in k for c in p], per=16)
    ct, cp = U.cursor_blob()
    b, a = pk.add('ui_cursor', ct)
    out.H('#define UI_CURS_BANK %d' % b)
    out.H('#define UI_CURS_ADDR 0x%04X' % a)
    out.arr('u16', 'ui_curs_pal', cp)
    pics = [('PG13', lambda: _pg13()), ('TITLE', lambda: (U.pic_rgb('TITLEPIC', 160, 144), 8, 0)),
            ('CREDITS', lambda: (U.pic_rgb('CREDITSPIC', 160, 144), 8, 0)),
            ('OPTIONS', lambda: (U.pic_rgb('C_OPTIONSPIC'), 2, 6)),
            ('FACE0', lambda: (U.pic_rgb('C_BABYMODEPIC'), 2, 6)), ('FACE1', lambda: (U.pic_rgb('C_EASYPIC'), 2, 6)),
            ('FACE2', lambda: (U.pic_rgb('C_NORMALPIC'), 2, 6)), ('FACE3', lambda: (U.pic_rgb('C_HARDPIC'), 2, 6)),
            ('FXT', lambda: (U.pic_rgb('C_FXTITLEPIC'), 2, 6)), ('DIGIT', lambda: (U.pic_rgb('C_DIGITITLEPIC'), 2, 6)),
            ('MUSICT', lambda: (U.pic_rgb('C_MUSICTITLEPIC'), 2, 6)),
            ('NSEL', lambda: (U.pic_rgb('C_NOTSELECTEDPIC'), 2, 6)), ('SEL', lambda: (U.pic_rgb('C_SELECTEDPIC'), 2, 6)),
            ('GUY1', lambda: (U.pic_rgb('L_GUYPIC', 56, 48), 3, 5)), ('GUY2', lambda: (U.pic_rgb('L_GUY2PIC', 56, 48), 3, 5)),
            ('BJWIN', lambda: (U.pic_rgb('L_BJWINSPIC', 56, 56), 3, 5)),
            ('PSYCHED', lambda: (U.pic_rgb('GETPSYCHEDPIC', 144, 32), 2, 6))]

    def _pg13():
        import numpy as np
        a = U.to_rgb(G.pic256('PG13PIC'))
        c = np.zeros((144, 160, 3), np.uint8)
        c[:] = a[0, 0]
        h, w = a.shape[:2]
        c[(144 - h) // 2:(144 - h) // 2 + h, (160 - w) // 2:(160 - w) // 2 + w] = a
        return c, 4, 0
    import gb_hicolor
    hb, ha = pk.add('hicolor_title', gb_hicolor.make_hicolor(U.pic_rgb('TITLEPIC', 160, 144))[0], align=16)
    out.H('#define HC_TITLE_BANK %d' % hb)
    out.H('#define HC_TITLE_ADDR 0x%04X' % ha)
    pic_loc = []
    names = []
    for nm, fn in pics:
        rgb, npal, pbase = fn()
        blob, nt = U.make_pic(rgb, npal, pbase)
        pic_loc.append(pk.add('pic_' + nm, blob, align=16))
        out.H('#define PIC_%s %d' % (nm, len(pic_loc) - 1))
    helppg = [U.scale_page(p) for p in U.render_pages(U.help_text())]
    endpg = [U.scale_page(p) for p in U.render_pages(U.end_text())]
    out.H('#define PIC_HELP0 %d' % len(pic_loc))
    out.H('#define NHELP %d' % len(helppg))
    for rgb in helppg:
        pic_loc.append(pk.add('pic_help', U.make_pic(rgb, 8, 0)[0], align=16))
    out.H('#define PIC_END0 %d' % len(pic_loc))
    out.H('#define NEND %d' % len(endpg))
    for rgb in endpg:
        pic_loc.append(pk.add('pic_end', U.make_pic(rgb, 8, 0)[0], align=16))
    out.arr('u8', 'pic_bank', [b for b, a in pic_loc], per=16)
    out.arr('u16', 'pic_addr', [a for b, a in pic_loc], per=10)
    out.H('#define NPICS %d' % len(pic_loc))

    import gb_audio
    gb_audio.build(pk, out, d)
    out.H('#define NUMMUSIC %d' % len(mus))
    pk_info = pk
    return out, pk


def main():
    out, pk = build()
    out.write()
    open(os.path.join(GEN, 'data.bin'), 'wb').write(pk.image())
    print('data banks:', pk.nbanks, '(banks %d..%d)' % (DATA_BANK0, DATA_BANK0 + pk.nbanks - 1))


if __name__ == '__main__':
    main()
